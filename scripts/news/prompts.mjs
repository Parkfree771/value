// ─── 1) 사이트용 10개 이슈 (project7 apps/1.briefing/analyze.js buildPrompt 원문) ───
export function buildBriefingPrompt(data, prev) {
  // 매체별 헤드라인 요약 목록
  const articleList = data.articles
    .map(
      (a, i) =>
        `${i + 1}. [${a.source}] ${a.title}\n   ${a.summary.slice(0, 200)}\n   Published: ${a.published}`
    )
    .join("\n\n");

  const prevSection = prev
    ? `
## 직전 브리핑 (반드시 차별화)
직전 발행 시각: ${prev.generated_at_kr || prev.generated_at}
직전에 다룬 10개 이슈 헤드라인:
${prev.issues.map((i, n) => `  ${n + 1}. ${i.headline}`).join("\n")}

**차별화 규칙 — 엄격히 적용:**
- 위에 나열된 이슈는 직전 브리핑이 이미 다룬 것입니다. **새로운 사실관계 변화(추가 수치 발표, 새 개입, 시장 반응 확정 등)가 분명히 있을 때만** 다시 채택하고, 그 경우에도 헤드라인은 "오늘의 새 전개"가 보이도록 다시 작성하세요.
- 직전과 사실상 같은 사건의 단순 후속 보도(논평, 재분석)는 제외하고, 그 자리는 RSS 풀에 있는 **그 다음 순위의 이슈**로 채우세요.
- 결과적으로 새 브리핑의 10개 이슈 중 직전과 동일 토픽은 최대 3개 이내가 되도록 하세요. 그게 어려우면 우선순위 원칙(매크로 > 산업/메가캡 > 개별주)을 다시 살펴 새 이슈를 적극 발굴하세요.
`
    : "";

  return `당신은 한국 투자자를 위한 글로벌 **경제·시장** 브리핑 애널리스트입니다. 결과물은 사이트와 인스타그램 카드뉴스에 동시 노출되므로 선정 품질이 매우 중요합니다.
${prevSection}
## 임무
아래 ${data.total_articles}개의 글로벌 메이저 매체 RSS 헤드라인을 분석하여, 오늘 가장 중요한 **경제·시장 이슈 정확히 10개**를 선정하세요.

## 대전제: 경제·시장 중심
- 이 브리핑은 **경제와 금융시장**에 관한 것입니다. 일반 정치·사회·문화 뉴스는 다루지 않습니다.
- 정치/지정학 뉴스는 **시장·경제에 직접적이고 큰 영향을 줄 때만** 채택합니다. 즉 "Brexit급" 사건이면 채택, "영국 총리 교체 가십"이나 "미 의회 일상 정쟁"은 제외.
- 판별 기준: 그 뉴스로 **지수·금리·환율·유가·실적이 실제로 움직이는가?** 움직이지 않으면 제외.

## 매체 중복 = 가장 강력한 중요도 신호 (핵심)
- **여러 매체가 같은 사건을 동시에 헤드라인으로 송출한다는 것 자체가 "시장이 합의한 큰 뉴스"라는 강력한 신호**입니다.
- 3개 이상 매체가 다룬 이슈 → 거의 확실한 1순위 후보.
- 1~2개 매체에서만 보이는 단발성 보도 → 그만큼 우선순위를 낮추세요.
- 실제 처리: 동일 이슈를 다룬 기사들을 먼저 그룹핑하고, 그룹의 **매체 수와 사건 자체의 시장 파급력** 두 축으로 정렬하세요.

## 우선순위 원칙

**1순위 — 글로벌 매크로·시장 전반 (적극 채택)**
- 주요국 통화정책: 연준·ECB·BOJ·BOE·PBoC 금리/QT 결정, 의장 발언, 회의록
- 거시지표: CPI·PCE·고용·GDP·PMI 등 시장 영향이 큰 지표 발표
- 원자재: 유가·천연가스·금·구리 등 시장 전반에 파급되는 흐름
- 통화·외환: USD/EUR/JPY/CNY 큰 흐름, 환율 개입
- 주요 지수의 의미있는 움직임 (S&P 500, Nasdaq, Stoxx 600, Nikkei, Hang Seng, KOSPI 등)
- **시장 영향이 명확한 정치/지정학**: 전쟁·제재·관세·교역분쟁, Brexit급 정치 이벤트, 주요 무역협정 체결/파기 등 (단순 정치 가십·국내 정쟁은 제외)

**2순위 — 산업·정책·메가캡 실적 (선별 채택)**
- 산업 전반에 영향을 주는 정책 (반도체 수출규제, EV·배터리 보조금, 빅테크 규제 등)
- 시총 상위 빅테크의 실적/가이던스 (Apple, Microsoft, NVIDIA, Google, Amazon, Meta 등 시장 전체를 움직일 수준일 때만)
- 대규모 M&A·IPO (수십억 달러 이상으로 산업 구조에 영향)

**3순위 — 기본적으로 제외**
- 개별 중·소형주의 단발성 등락
- 특정 펀드매니저·투자자의 단일 포지션 변동 (예: "빌 애크먼이 들고 있던 IPO 종목 급락" 류 — 시장 전체 영향이 미미하면 무조건 제외)
- 시장 파급력이 약한 개별 기업 가십성 보도, 인사 이동
- 비경제 정치/사회/문화 뉴스 (선거 일정·정치 가십·연예·스포츠 등 시장과 무관한 모든 것)
- 위 항목들은 정말로 시장 전체를 흔드는 수준이 아니면 절대 채택하지 마세요.

## 지역 비중
- **미국 비중은 충분히 유지하세요.** 미국이 글로벌 자본시장에 가장 큰 영향을 주므로 미국발 매크로·정책·메가캡 실적 이슈는 자연스럽게 큰 비중을 차지합니다.
- 다만 미국 **일변도**가 되어선 안 됩니다. 그 날 의미있는 비미국 이슈(유럽·일본·중국·신흥국의 매크로/정책/주요 사건)가 있으면 반드시 함께 포함하세요.
- "균형"의 의미: 미국을 깎으라는 게 아니라, 비미국도 시장 영향이 크면 챙기라는 뜻.

## 저작권·표절 방지 (가장 중요)
- RSS 원문을 그대로 번역하거나 단어만 바꾸는 패러프레이징은 절대 금지.
- 절차: 여러 기사에서 **사실(수치·고유명사·이벤트)** 만 추출 → 원문을 덮고 → **문장 구조와 순서를 원문과 다르게** 처음부터 자기 말로 한국어로 서술.
- 원문 특유의 수식어·비유·강조 표현 사용 금지. 결과물은 원문과 문장 수준에서 완전히 달라야 합니다.

## 출력 규칙
- 위 원칙에 따라 **자기 말로** 한국어 브리핑을 작성.
- 각 이슈: 무슨 일이 있었고, 시장에 어떤 영향을 줬는지 2~3문장으로 정리.
- 태그는 다음 중 선택: 매크로, 연준, 중앙은행, 실적, 관세, 지정학, 원자재, 테크, 크립토, IPO, 정책, 외환, 아시아, 유럽
- covered_by: 이 이슈를 다룬 매체 이름 목록.
- sources: 공식 1차 소스로 표기 (예: "SEC 공시", "백악관 발표", "시장 데이터 기반").

## 정렬 (엄격)
- **issues 배열의 1번 = 오늘 가장 중요한 이슈, 10번 = 상대적으로 덜 중요한 이슈**.
- 위 우선순위 원칙(글로벌 매크로 > 산업/메가캡 > 개별주)과 매체 보도 수를 종합해 엄격히 내림차순 정렬.

반드시 아래 JSON 형식으로만 출력하세요. 다른 텍스트 없이:

{
  "issues": [
    {
      "headline": "한국어 헤드라인 (자기 말로, 번역 아님)",
      "summary": "2~3문장 브리핑 (자기 말로 작성. RSS 원문 번역 금지)",
      "tags": ["태그1", "태그2"],
      "covered_by": ["Bloomberg", "WSJ", "CNBC"],
      "sources": "출처 표기 (예: 시장 데이터 기반, SEC 공시 기반)",
      "importance": "high | medium | low"
    }
  ]
}

이슈는 정확히 10개를 선별하고, 위 우선순위 원칙에 따라 중요도 내림차순(1번이 가장 중요)으로 정렬하세요.

## RSS 헤드라인 목록 (${data.total_articles}건)

${articleList}`;
}

// ─── 2) 인스타 카드 5장 카피 (project7 apps/2.instagram/rewrite_hooks.js 기반, 10개 → 가장 핫한 5개) ───
export function buildHooksPrompt(briefing) {
  const issueList = briefing.issues
    .map((it, i) => `${i + 1}. [${(it.tags || []).join(', ')}] ${it.headline}\n   요약: ${it.summary}\n   보도 매체: ${(it.covered_by || []).length}곳`)
    .join('\n\n');

  return `당신은 antstreet 인스타그램 캐러셀 카피라이터입니다.

## 임무
오늘의 글로벌 시장 브리핑 ${briefing.issues.length}개 이슈 중 **인스타그램에 올릴 5개**를 고르고, 카드 뉴스용으로 리라이팅하세요.
카드는 정확히 5장입니다. 같은 5장이 캐러셀 게시물과 릴스(세로 영상)에 그대로 쓰입니다.

## 5개 고르는 기준 — "가장 핫한" 이슈
- 한국 개인 투자자가 **오늘 가장 궁금해하고, 저장·공유하고 싶어 할** 이슈를 고르세요.
- 우선 기준: 많은 매체가 다뤘고(시장 합의) + 내 계좌에 바로 닿는 이슈 (금리·환율·유가·빅테크·반도체·관세·한국/미국 증시).
- 원래 순위(1번이 가장 중요)를 존중하되, 같은 주제가 겹치면 하나만 남기고 다른 축의 이슈로 채우세요.
- 5장이 모두 미국 이슈일 필요는 없습니다. 의미 있는 비미국 이슈가 있으면 넣으세요.

## 톤
- 정보 전달형 — 자극적·선정적 X. antstreet은 신뢰감 있는 금융 브리핑 브랜드입니다.
- 헤드라인은 18~26자 사이, 카드에서 두 줄 안에 들어가야 합니다.
- 원문 헤드라인보다 **사용자가 더 클릭/저장하고 싶게** 만드세요. 다만 과장은 금지.
- 호기심 유발은 OK ("왜?", "이유는?", "지금?") 하지만 낚시·과장·이모지 X.

## 표지 카피
- 고른 5개 중 첫 카드(가장 핫한 이슈)를 기반으로, 1번 카드 위쪽에 들어갈 짧은 임팩트 한 줄(20자 이내)을 추가로 생성.
- 날짜와 함께 보이므로, 헤드라인보다 더 압축적이어야 함.

## 본문 카드 요약
- 각 카드 본문에 들어갈 2~3문장 요약(80~140자)을 만드세요.
- 원본 summary 를 참조하되, 인스타에서 읽기 좋게 짧게 다듬으세요. 숫자(%, 금리, 가격)가 있으면 살리세요.

## 출력
반드시 아래 JSON 형식으로만, 다른 텍스트 없이:

{
  "cover_hook": "표지용 임팩트 한 줄 (20자 이내)",
  "cards": [
    {
      "index": 3,
      "tag": "대표 태그 1개 (예: 매크로, 연준, 실적, 관세, 지정학, 원자재, 테크, 외환)",
      "headline": "인스타 후킹 헤드라인 (18~26자)",
      "summary": "카드 본문 요약 2~3문장 (80~140자)"
    }
  ]
}

cards 배열은 정확히 5개. index 는 원본 이슈 번호(1~${briefing.issues.length}), 카드 순서는 가장 핫한 것부터.

## 원본 이슈 목록 (1번이 가장 중요)

${issueList}`;
}

// ─── 3) 인스타 캡션 (project7 apps/2.instagram/make_caption.js 기반, TOP 5 + 사이트 10개 안내) ───
export function buildCaptionPrompt(cards, dateStr, briefingUrl) {
  const cardsText = cards.map((c, i) => `${i + 1}. ${c.headline}\n   ${c.summary}`).join('\n\n');

  return `당신은 antstreet 인스타그램 캡션 카피라이터입니다. 아래 오늘의 인스타 카드 5장을 보고, 인스타그램 게시물 본문(캡션)을 **한 덩어리의 텍스트로** 작성하세요. 사용자가 복붙해서 바로 게시물에 올릴 형태입니다.

## 브랜드/톤
- 신뢰감 있는 글로벌 경제 브리핑. 자극적·선정적 표현 금지.
- 이모지 1~2개까지만 절제해서 사용 (없어도 됨).
- 한국어. 존댓말 종결("~합니다") 또는 명사형으로 깔끔하게.

## 캡션 구조 (정확히 이 순서, 각 블록 사이는 빈 줄 1개로 구분)
1) **첫 줄(타이틀)**: 날짜 + 한 줄 타이틀. 정확히 이 형식: "${dateStr} 오늘의 경제 이슈 TOP 5"
   (날짜 뒤에는 점·하이픈·중점 같은 구분기호 없이 공백 하나만)
2) **핵심 5줄**: 카드 5장의 이슈를 한 줄씩, 카드 순서대로. 각 줄은 정확히 "• " 로 시작. 각 줄 최대 30자 내외. 시장이 무엇 때문에 움직였는지/핵심 사실이 보이게 압축.
3) **마무리 한 줄**: 정확히 이 형식: "10개 이슈 전체 브리핑 → ${briefingUrl}"
4) **해시태그 줄**: 한 줄에 10~12개, 모두 공백으로 구분. 너무 큰 태그(#news 등)는 피하고, 오늘 이슈와 직접 관련된 키워드 위주(#연준 #금리 #FOMC #실적 #원유 등). 마지막 두 개는 반드시 #앤트스트리트 #글로벌경제 포함.

## 분량/형식 규칙
- 전체 길이는 짧고 깔끔하게. 인스타 피드에서 "더보기" 누르기 전 4~5줄 안에 핵심이 보이도록.
- 장황한 설명·중복 금지. 뉴스 분석 톤 X, 헤드라인 정리 톤 O.
- 마크다운(**, ##, - 등) 사용 금지. 일반 텍스트만.
- 출력은 캡션 본문 자체만. 따옴표·코드블록·"캡션:" 같은 라벨 없이 바로 본문부터.

## 오늘의 날짜
${dateStr}

## 오늘의 카드 5장 (카드 순서대로)
${cardsText}
`;
}
